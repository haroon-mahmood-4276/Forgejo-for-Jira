/** A small upper-case section label, like "BUILDS". */
const sectionLabel = (x, y, label) =>
  text(x, y, label.toUpperCase(), { size: 14, weight: 700, fill: C.faint, spacing: 1.2 });

/** The "Forgejo" source label shown at the right of a Development panel header. */
function sourceLabel(rightEdge, baseline, scale = 1) {
  const label = 'Forgejo';
  const labelWidth = textWidth(label, 16 * scale);
  const markSize = 28 * scale;
  return (
    forgejoMark(rightEdge - labelWidth - 8 - markSize, baseline - 21 * scale, markSize) +
    text(rightEdge, baseline, label, { size: 16 * scale, fill: C.muted, anchor: 'end' })
  );
}

/** A tall tab strip for the admin page. Returns the SVG and where the active tab sits. */
function adminTabs(x, y, activeIndex) {
  const labels = ['Connect to Forgejo', 'Repositories', 'Builds & deployments'];
  let cursor = x;
  let out = '';
  let underline = '';
  labels.forEach((label, i) => {
    const w = textWidth(label, 16, { weight: i === activeIndex ? 600 : 400 });
    out += text(cursor, y, label, {
      size: 16,
      weight: i === activeIndex ? 600 : 400,
      fill: i === activeIndex ? C.blue : C.muted,
    });
    if (i === activeIndex) underline = rect(cursor, y + 15, w, 4, { fill: C.blue });
    cursor += w + 32;
  });
  return out + underline;
}

/**
 * A single line of text made of styled runs. Each run is [string, style] where
 * style is 'bold' or 'code' (or omitted for plain text). Using <tspan>s lets the
 * browser place each run after the previous one, which we cannot do reliably by
 * estimating text widths ourselves.
 */
function richText(x, y, runs, size = 16) {
  const spans = runs
    .map(([str, style]) => {
      if (style === 'bold') return `<tspan font-weight="700">${esc(str)}</tspan>`;
      if (style === 'code') {
        return `<tspan font-family="${MONO}" font-size="${size - 1}" fill="#42526e">${esc(str)}</tspan>`;
      }
      return `<tspan>${esc(str)}</tspan>`;
    })
    .join('');
  return (
    `<text x="${x}" y="${y}" font-family="${FONT}" font-size="${size}" fill="${C.ink}" ` +
    `xml:space="preserve" style="white-space:pre">${spans}</text>`
  );
}

/** A left-to-right row of small blue pills, such as webhook event names. */
function eventPills(x, y, labels) {
  let cursor = x;
  return labels
    .map((label) => {
      const w = textWidth(label, 14, { weight: 600 }) + 24;
      const out =
        rect(cursor, y, w, 30, { r: 15, fill: C.blueBg }) +
        text(cursor + w / 2, y + 20, label, { size: 14, weight: 600, fill: C.blue, anchor: 'middle' });
      cursor += w + 10;
      return out;
    })
    .join('');
}

/** A node in a deployment pipeline: a coloured disc with a state icon. */
function pipelineNode(cx, cy, r, state) {
  if (state === 'success') {
    return (
      circle(cx, cy, r, C.green) +
      `<path d="M${cx - r * 0.38} ${cy + r * 0.02} L${cx - r * 0.1} ${cy + r * 0.3} L${cx + r * 0.42} ${cy - r * 0.28}" ` +
      `fill="none" stroke="#fff" stroke-width="${r * 0.15}" stroke-linecap="round" stroke-linejoin="round"/>`
    );
  }
  // "running": a ring with an upward arrow.
  return (
    circle(cx, cy, r, C.blueBg, `stroke="${C.blue}" stroke-width="${r * 0.12}"`) +
    icon('deploy', cx - r * 0.5, cy - r * 0.5, r, C.blue, 2.4)
  );
}

/** YAML colouring: comments grey, keys blue, values orange. Returns [text, colour] pairs. */
const CODE = { plain: '#e2e8f0', comment: '#7384a6', key: '#7dd3fc', value: '#fdba74' };
function yamlSegments(raw) {
  if (/^\s*#/.test(raw)) return [[raw, CODE.comment]];
  const m = raw.match(/^(\s*)(- )?([\w.-]+:)(.*)$/);
  if (!m) return [[raw, CODE.plain]];
  const segments = [[m[1] + (m[2] ?? ''), CODE.plain], [m[3], CODE.key]];
  if (m[4]) segments.push([m[4], CODE.value]);
  return segments;
}

/** One line of monospace code made of coloured segments. */
function codeLine(x, y, raw, size = 17) {
  const spans = yamlSegments(raw)
    .map(([str, fill]) => `<tspan fill="${fill}">${esc(str)}</tspan>`)
    .join('');
  return (
    `<text x="${x}" y="${y}" font-family="${MONO}" font-size="${size}" ` +
    `xml:space="preserve" style="white-space:pre">${spans}</text>`
  );
}

